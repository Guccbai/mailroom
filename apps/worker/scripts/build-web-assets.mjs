const isBinary = (type) => type.startsWith('font/')

export function generatedSource() {
  const entries = Object.entries(files).map(([path, [file, type]]) => {
    const bytes = readFileSync(join(root, 'web', file))
    const etag = createHash('sha256').update(bytes).digest('hex').slice(0, 16)
    const binary = isBinary(type)
    const body = binary ? bytes.toString('base64') : bytes.toString('utf8')
    return `  ${JSON.stringify(path)}: {\n    type: ${JSON.stringify(type)},\n    etag: ${JSON.stringify(`"${etag}"`)},${binary ? '\n    base64: true,' : ''}\n    body: ${JSON.stringify(body)},\n  },`
  })
  return `// Generated by scripts/build-web-assets.mjs from apps/worker/web. Do not edit.\nexport const WEB_ASSETS: Record<\n  string,\n  { type: string; etag: string; base64?: boolean; body: string }\n> = {\n${entries.join('\n')}\n}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(root, 'src', 'web-assets.generated.ts')
  writeFileSync(target, generatedSource())
  console.log(`Wrote ${target}`)
}

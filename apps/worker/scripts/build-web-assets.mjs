// Embed the static web app in the Worker bundle. Run after editing web/.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const files = {
  '/index.html': ['index.html', 'text/html; charset=utf-8'],
  '/app.js': ['app.js', 'text/javascript; charset=utf-8'],
  '/lib.js': ['lib.js', 'text/javascript; charset=utf-8'],
  '/layout.js': ['layout.js', 'text/javascript; charset=utf-8'],
  '/mail.js': ['mail.js', 'text/javascript; charset=utf-8'],
  '/drafts.js': ['drafts.js', 'text/javascript; charset=utf-8'],
  '/settings.js': ['settings.js', 'text/javascript; charset=utf-8'],
  '/app.css': ['app.css', 'text/css; charset=utf-8'],
  '/favicon.svg': ['favicon.svg', 'image/svg+xml'],
}

export function generatedSource() {
  const entries = Object.entries(files).map(([path, [file, type]]) => {
    const body = readFileSync(join(root, 'web', file), 'utf8')
    const etag = createHash('sha256').update(body).digest('hex').slice(0, 16)
    return `  ${JSON.stringify(path)}: {\n    type: ${JSON.stringify(type)},\n    etag: ${JSON.stringify(`"${etag}"`)},\n    body: ${JSON.stringify(body)},\n  },`
  })
  return `// Generated by scripts/build-web-assets.mjs from apps/worker/web. Do not edit.\nexport const WEB_ASSETS: Record<\n  string,\n  { type: string; etag: string; body: string }\n> = {\n${entries.join('\n')}\n}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(root, 'src', 'web-assets.generated.ts')
  writeFileSync(target, generatedSource())
  console.log(`Wrote ${target}`)
}
